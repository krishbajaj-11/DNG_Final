logger = logging.getLogger(__name__)


# ------------------------------------------------------------------
# ImageNet normalization constants
# ------------------------------------------------------------------
IMAGENET_MEAN = [0.485, 0.456, 0.406]
IMAGENET_STD  = [0.229, 0.224, 0.225]


# ------------------------------------------------------------------
# Synthetic dataset generator (for when you don't have DNG files yet)
# ------------------------------------------------------------------

def generate_synthetic_dataset(
    output_dir: str,
    num_images: int = 500,
    num_levels: int = 10,
    img_size: int = 512,
) -> str:
    """
    Generate a synthetic dataset of images at varying detail levels.
    Each image is a clean source degraded by increasing amounts of noise/blur.

    Directory structure:
        output_dir/
            level_01/image_001.png  ...
            level_02/image_001.png  ...
            ...
            level_10/image_001.png  ...
            labels.json
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    labels: Dict[str, int] = {}
    rng = np.random.default_rng(42)

    print(f"Generating {num_images} synthetic images across {num_levels} levels...")

    for level in range(1, num_levels + 1):
        level_dir = output_dir / f"level_{level:02d}"
        level_dir.mkdir(exist_ok=True)

        for i in range(num_images // num_levels):
            # Create a rich synthetic image (textures + gradients)
            base = rng.random((img_size, img_size, 3), dtype=np.float32)
            # Add structured patterns
            x = np.linspace(0, 4 * np.pi, img_size)
            pattern = np.sin(x[np.newaxis, :] * level) * np.cos(x[:, np.newaxis] * level)
            base[:, :, 0] += pattern * 0.3
            base = np.clip(base, 0, 1)

            # Degrade based on level (level 1 = most degraded, level 10 = sharpest)
            degraded = _degrade_image(base, quality_level=level, num_levels=num_levels, rng=rng)

            fname = f"img_{i:04d}.png"
            fpath = level_dir / fname
            cv2.imwrite(str(fpath), (degraded * 255).astype(np.uint8))

            rel_path = str(Path(f"level_{level:02d}") / fname)
            labels[rel_path] = level  # 1-indexed level label

    labels_path = output_dir / "labels.json"
    with open(labels_path, "w") as f:
        json.dump(labels, f, indent=2)

    print(f"Dataset saved to {output_dir}")
    print(f"Labels saved to {labels_path}")
    return str(output_dir)


def _degrade_image(
    image: np.ndarray,
    quality_level: int,
    num_levels: int,
    rng: np.random.Generator,
) -> np.ndarray:
    """
    Apply degradation inversely proportional to quality level.
    Level 1 (worst) = heavy blur + noise. Level 10 (best) = clean.
    """
    # Fraction of degradation: 1.0 at level 1, ~0 at level num_levels
    deg_factor = 1.0 - (quality_level - 1) / (num_levels - 1)

    result = image.copy()

    # Gaussian blur
    blur_sigma = deg_factor * 4.0
    if blur_sigma > 0.3:
        ksize = int(blur_sigma * 3) * 2 + 1
        result = cv2.GaussianBlur(result, (ksize, ksize), blur_sigma)

    # Additive Gaussian noise
    noise_std = deg_factor * 0.12
    if noise_std > 0:
        noise = rng.normal(0, noise_std, result.shape).astype(np.float32)
        result = np.clip(result + noise, 0, 1)

    return result.astype(np.float32)


