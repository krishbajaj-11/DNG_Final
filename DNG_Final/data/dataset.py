# PyTorch Dataset
# ------------------------------------------------------------------

class DNGDetailDataset(Dataset):
    """
    Dataset that reads preprocessed PNG images from a directory structure
    generated by `build_fivek_dataset.py`.

    Supports both full 1–10 and partial 5–10 label ranges.
    Labels are always remapped to 0-indexed classes for training.
    e.g. {5,6,7,8,9,10} → {0,1,2,3,4,5}  (6 classes)

    Each sample: (tensor [3, H, W], class_index int)
    """

    def __init__(
        self,
        data_dir: str,
        labels_file: str = "labels.json",
        split: str = "train",
        num_levels: int = 10,
        img_size: int = 224,
        augment: bool = True,
    ):
        self.data_dir = Path(data_dir)
        self.num_levels = num_levels
        self.split = split

        # Load labels
        labels_path = self.data_dir / labels_file
        with open(labels_path) as f:
            all_labels: Dict[str, int] = json.load(f)

        # Discover unique label values and remap to 0-indexed classes
        unique_levels = sorted(set(all_labels.values()))
        self.level_to_class = {lv: i for i, lv in enumerate(unique_levels)}
        self.class_to_level = {i: lv for lv, i in self.level_to_class.items()}
        num_classes = len(unique_levels)
        logger.info(f"Levels in dataset: {unique_levels} → {num_classes} classes")
        # Split data
        items = list(all_labels.items())
        random.seed(42)
        random.shuffle(items)

        n = len(items)
        if split == "train":
            items = items[: int(0.8 * n)]
        elif split == "val":
            items = items[int(0.8 * n): int(0.9 * n)]
        else:  # test
            items = items[int(0.9 * n):]

        self.samples: List[Tuple[Path, int]] = [
            (self.data_dir / rel, self.level_to_class[label])
            for rel, label in items
            if label in self.level_to_class
        ]

        # Transforms
        if augment and split == "train":
            self.transform = transforms.Compose([
                transforms.ToPILImage(),
                transforms.RandomResizedCrop(img_size, scale=(0.8, 1.0)),
                transforms.RandomHorizontalFlip(),
                transforms.RandomVerticalFlip(),
                transforms.ColorJitter(brightness=0.2, contrast=0.2, saturation=0.1),
                transforms.ToTensor(),
                transforms.Normalize(mean=IMAGENET_MEAN, std=IMAGENET_STD),
            ])
        else:
            self.transform = transforms.Compose([
                transforms.ToPILImage(),
                transforms.Resize((img_size, img_size)),
                transforms.ToTensor(),
                transforms.Normalize(mean=IMAGENET_MEAN, std=IMAGENET_STD),
            ])

        logger.info(f"DNGDetailDataset [{split}]: {len(self.samples)} samples")

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, int]:
        img_path, label = self.samples[idx]
        img_bgr = cv2.imread(str(img_path))
        if img_bgr is None:
            raise RuntimeError(f"Failed to load image: {img_path}")
        img_rgb = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)
        tensor = self.transform(img_rgb)
        return tensor, label


def create_dataloaders(
    data_dir: str,
    batch_size: int = 32,
    num_workers: int = 4,
    img_size: int = 224,
    num_levels: int = 10,
) -> Tuple[DataLoader, DataLoader, DataLoader]:
    """Create train/val/test DataLoaders."""
    train_ds = DNGDetailDataset(data_dir, split="train", img_size=img_size, num_levels=num_levels)
    val_ds   = DNGDetailDataset(data_dir, split="val",   img_size=img_size, num_levels=num_levels, augment=False)
    test_ds  = DNGDetailDataset(data_dir, split="test",  img_size=img_size, num_levels=num_levels, augment=False)

    train_loader = DataLoader(train_ds, batch_size=batch_size, shuffle=True,  num_workers=num_workers, pin_memory=True)
    val_loader   = DataLoader(val_ds,   batch_size=batch_size, shuffle=False, num_workers=num_workers, pin_memory=True)
    test_loader  = DataLoader(test_ds,  batch_size=batch_size, shuffle=False, num_workers=num_workers, pin_memory=True)

    return train_loader, val_loader, test_loader


